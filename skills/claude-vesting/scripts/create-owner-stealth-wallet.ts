/**
 * create-owner-stealth-wallet.ts — agent-generated stealth wallet
 * (EXPLICIT TRUST OPT-IN — read the warning before use).
 *
 * For owners who want zero setup and accept the trust tradeoff: the
 * AGENT generates a stealth wallet (ERC-5564 spending + viewing keys)
 * for the owner, keeps only the meta-address for forwarding, and hands
 * the owner a recovery file holding the keys.
 *
 * THE TRADEOFF, stated plainly (the skill requires the agent to say
 * this to the human BEFORE generating): whoever generates these keys
 * can scan and spend everything this wallet ever receives, forever.
 * Deleting the generator's copy reduces live risk but can never be
 * proven. This mode is for convenience amounts and for humans who
 * trust their agent like a bank — never the default. The default is
 * owner-born keys (the human's own vault generates; the agent only
 * ever sees the meta-address).
 *
 * Behavior:
 * - Refuses to overwrite an existing recovery file.
 * - Writes the recovery file 0600. The private keys are NEVER printed
 *   to stdout/logs — the file is the handover, deliver it to the human
 *   and have them store it offline.
 * - Prints only the meta-address (safe to share — it's the public
 *   half) and the trust warning.
 *
 * Usage:
 *   OWNER_WALLET_OUT=./owner-stealth-recovery.json \
 *   npx hardhat run skills/claude-vesting/scripts/create-owner-stealth-wallet.ts --network base
 */
import { ethers } from "hardhat";
import { secp256k1 } from "@noble/curves/secp256k1";
import * as fs from "fs";

export const TRUST_WARNING =
  "TRUST OPT-IN: this stealth wallet was generated by your agent. Whoever generates " +
  "stealth keys can scan and spend everything the wallet receives, forever — deleting " +
  "the generator's copy cannot be proven. Use it for convenience amounts only, and " +
  "migrate to a wallet you generated yourself (owner-born keys) for anything serious.";

function randomScalar(): bigint {
  return BigInt(ethers.Wallet.createRandom().privateKey);
}

function compressedHex(scalar: bigint): string {
  const pt = secp256k1.ProjectivePoint.BASE.multiply(scalar);
  return Buffer.from(pt.toRawBytes(true)).toString("hex");
}

async function main() {
  const out = process.env.OWNER_WALLET_OUT ?? "./owner-stealth-recovery.json";
  if (fs.existsSync(out)) {
    throw new Error(`Refusing to overwrite existing recovery file: ${out}`);
  }
  const spendPriv = randomScalar();
  const viewPriv = randomScalar();
  const meta =
    "st:eth:0x" + compressedHex(spendPriv) + compressedHex(viewPriv);

  const recovery = {
    kind: "proof-of-dev/agent-generated-stealth-wallet",
    version: 1,
    created: new Date().toISOString(),
    stealth_meta_address: meta,
    stealth_spending_priv: "0x" + spendPriv.toString(16).padStart(64, "0"),
    stealth_viewing_priv: "0x" + viewPriv.toString(16).padStart(64, "0"),
    trust_warning: TRUST_WARNING,
    how_to_use:
      "With these two private keys, any ERC-5564 tooling (e.g. Agent Private Pay's " +
      "scan/sweep) can discover payments to the meta-address and spend them. " +
      "Whoever holds this file controls the wallet — store it offline.",
  };
  fs.writeFileSync(out, JSON.stringify(recovery, null, 2) + "\n", { mode: 0o600 });

  console.log("agent-generated stealth wallet created (TRUST OPT-IN)");
  console.log("meta-address (shareable, this is all the agent keeps):", meta);
  console.log("recovery file (HAND TO THE HUMAN, never print its contents):", out);
  console.log("warning the human must hear:", TRUST_WARNING);
}

main().catch((e) => { console.error(e); process.exitCode = 1; });
